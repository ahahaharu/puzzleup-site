/** «Всё сложится.» → строки «Всё» и «сложится» и точка в конце, которую красят в accent. */
export function splitSlogan(slogan: string): { lines: string[]; dot: string } {
  const dot = /[.!…]$/.exec(slogan)?.[0] ?? '';
  const body = dot ? slogan.slice(0, -dot.length) : slogan;
  return { lines: body.split(/\s+/).filter(Boolean), dot };
}
